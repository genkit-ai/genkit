ai.defineFlow(
  'streaming-thoughts',
  async (promptInput: string | undefined, { sendChunk }) => {
    const prompt =
      promptInput ??
      'Which is larger, 9.11 or 9.9? Explain your reasoning step by step.';

    const { stream, response } = ai.generateStream({
      model: googleAI.model('gemini-flash-latest'),
      prompt,
      config: {
        thinkingConfig: {
          includeThoughts: true,
          thinkingLevel: 'HIGH',
        },
      },
    });

    // Thought summaries and the answer arrive as separate chunk parts.
    for await (const chunk of stream) {
      if (chunk.reasoning) {
        sendChunk({ type: 'thought', text: chunk.reasoning });
      }
      if (chunk.text) {
        sendChunk({ type: 'text', text: chunk.text });
      }
    }

    return (await response).text;
  }
);

